const assert=require('node:assert/strict');
const gear=require('../desktop/assets/gear-planner.js');
const ring={id:12001,name:'Yuria Ring',mainCategory:20,subCategory:1,enhance:5,caphras:0};
assert(gear.fits(ring,gear.slots.find(s=>s[0]==='ring1')));
assert(gear.fits(ring,gear.slots.find(s=>s[0]==='ring2')));
assert(!gear.fits(ring,gear.slots.find(s=>s[0]==='helmet')));
const rows=[{minEnhance:0,maxEnhance:3,basePrice:100},{minEnhance:4,maxEnhance:4,basePrice:500},{minEnhance:5,maxEnhance:5,basePrice:1000}];
assert.equal(gear.priceFor(rows,2),100);
assert.equal(gear.priceFor(rows,5),1000);
assert.equal(gear.priceFor(rows,6),null);
assert.equal(gear.importEnhancement({kind:'roman',value:5},rows),5);
assert.equal(gear.importEnhancement({kind:'roman',value:5},[{minEnhance:20,maxEnhance:20,basePrice:2}]),20);
assert.equal(gear.importEnhancement(null,rows),null);
const state=gear.sanitizeState({active:'a',builds:[{id:'a',name:'Two rings',current:{ring1:ring,ring2:ring,helmet:ring},target:{ring2:{...ring,enhance:4}},sheet:{ap:310,dp:99999}}]});
assert(!state.builds[0].current.helmet);
assert.equal(state.builds[0].sheet.dp,null);
assert.equal(state.builds[0].sheet.ap,310);
assert.equal(gear.sanitizeState(gear.sanitizeState(null)).builds[0].sheet.ap,null);
const total=gear.totals(state.builds[0],x=>gear.priceFor(rows,x.enhance));
assert.deepEqual(total,{current:2000,target:1500,buy:500,missing:0,changed:1,buyMissing:0});
assert.equal(gear.totals(state.builds[0],()=>null).current,0);
assert(gear.totals(state.builds[0],()=>null).missing>0);
const caphrasOnly={current:{ring1:ring},target:{ring1:{...ring,caphras:15}}};
assert.equal(gear.totals(caphrasOnly,()=>1000).buy,0);
const untradeable={id:12294,name:'Kharazad Belt',mainCategory:20,subCategory:4,enhance:5,caphras:0,marketListed:false,maxEnhance:10};
const restored=gear.sanitizeState({builds:[{id:'kharazad',current:{belt:untradeable},target:{}}]});
assert.equal(restored.builds[0].current.belt.marketListed,false);
assert.equal(restored.builds[0].current.belt.maxEnhance,10);
assert.equal(gear.totals({current:{},target:{belt:untradeable}},()=>null).buyMissing,1);
assert.equal(gear.sanitizeState({builds:Array(30).fill(state.builds[0])}).builds.length,1);
console.log('Gear core: slot identity, duplicate accessories, enhancement ranges, import levels, partial valuations and bounded backups passed');
